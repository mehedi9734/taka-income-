create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'member' check (role in ('member','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  pay_bdt numeric(12,2) not null default 0 check (pay_bdt >= 0),
  is_open boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.applications (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id),
  user_id uuid not null references public.profiles(id) on delete cascade,
  note text,
  status text not null default 'submitted' check (status in ('submitted','reviewing','accepted','rejected','completed')),
  created_at timestamptz not null default now()
);
create table if not exists public.earnings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount_bdt numeric(12,2) not null check (amount_bdt >= 0),
  description text not null,
  status text not null default 'approved' check (status in ('pending','approved','paid','reversed')),
  created_at timestamptz not null default now()
);
create table if not exists public.withdrawal_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount_bdt numeric(12,2) not null check (amount_bdt > 0),
  method text not null check (method in ('bKash','Nagad','Bank transfer')),
  account_reference text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected','paid')),
  created_at timestamptz not null default now()
);
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles(id,full_name) values(new.id, coalesce(new.raw_user_meta_data->>'full_name','Member'));
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.tasks enable row level security;
alter table public.applications enable row level security;
alter table public.earnings enable row level security;
alter table public.withdrawal_requests enable row level security;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles where id=auth.uid() and role='admin'); $$;

create policy "profiles read self or admin" on public.profiles for select to authenticated
using (id=auth.uid() or public.is_admin());
create policy "profiles update self basic" on public.profiles for update to authenticated
using (id=auth.uid()) with check (id=auth.uid() and role='member');
create policy "tasks public read open" on public.tasks for select
using (is_open=true or public.is_admin());
create policy "tasks admin insert" on public.tasks for insert to authenticated
with check (public.is_admin());
create policy "tasks admin update" on public.tasks for update to authenticated
using (public.is_admin()) with check (public.is_admin());
create policy "tasks admin delete" on public.tasks for delete to authenticated
using (public.is_admin());
create policy "applications insert own" on public.applications for insert to authenticated
with check (user_id=auth.uid());
create policy "applications read own or admin" on public.applications for select to authenticated
using (user_id=auth.uid() or public.is_admin());
create policy "applications admin update" on public.applications for update to authenticated
using (public.is_admin()) with check (public.is_admin());
create policy "earnings read own or admin" on public.earnings for select to authenticated
using (user_id=auth.uid() or public.is_admin());
create policy "earnings admin insert" on public.earnings for insert to authenticated
with check (public.is_admin());
create policy "earnings admin update" on public.earnings for update to authenticated
using (public.is_admin()) with check (public.is_admin());
create policy "withdrawal insert own" on public.withdrawal_requests for insert to authenticated
with check (user_id=auth.uid());
create policy "withdrawal read own or admin" on public.withdrawal_requests for select to authenticated
using (user_id=auth.uid() or public.is_admin());
create policy "withdrawal admin update" on public.withdrawal_requests for update to authenticated
using (public.is_admin()) with check (public.is_admin());

